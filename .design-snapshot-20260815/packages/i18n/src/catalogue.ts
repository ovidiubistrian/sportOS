/**
 * Every catalogue has exactly the shape of the English one — the same sections
 * and the same keys — while being free to hold different strings.
 *
 * The widening matters: `as const` on the English catalogue types each value as
 * its own literal, so without this a Romanian translation would be rejected for
 * not being the English sentence. What we want to enforce is the *shape*, so a
 * missing or misspelt key is a compile error and a different wording is not.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

export type Catalogue = Widen<typeof en>;
