/**
 * The message catalogue.
 *
 * English is the source: it is the only catalogue typed by hand, and every
 * other language is checked against its shape at compile time. A missing
 * Romanian key is a type error, not a screen that silently shows an English
 * word in the middle of a Romanian sentence.
 *
 * Keys are namespaced by where they appear, not by what they say. `nav.players`
 * survives a copy change; `players` as a key does not survive the day someone
 * needs a second word for the same thing.
 *
 * Interpolation is `{name}`. There is no logic in a message — no nesting, no
 * conditionals — because a translator should never have to read code. Plurals
 * are separate keys (`one` / `other`) chosen by `plural()`, which is what lets
 * Romanian's three-way rule work without the English catalogue knowing about it.
 */

